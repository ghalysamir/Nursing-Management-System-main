let currentLang = "en";

function t(key, fallback = "") {
  const dict = translations[currentLang] || translations.en;
  if (key.includes(".")) {
    const parts = key.split(".");
    let val = dict;
    for (const p of parts) {
      val = val?.[p];
      if (val === undefined) break;
    }
    if (val !== undefined) return val;
    return fallback || key;
  }
  return dict[key] ?? translations.en[key] ?? fallback ?? key;
}

function setLanguage(lang) {
  if (!["en", "ar"].includes(lang)) lang = "en";
  currentLang = lang;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.style.fontFamily = lang === "ar"
    ? "var(--font-ar)"
    : "var(--font)";

  Store.setLang(lang);

  applyTranslations();

  const label = $("#currentLangLabel");
  if (label) label.textContent = lang.toUpperCase();
  const loginBtns = $$(".login-lang-switch .lang-btn");
  loginBtns.forEach(b => b.classList.toggle("active", b.dataset.lang === lang));
}

function applyTranslations(root = document) {
  $$("[data-i18n]", root).forEach(el => {
    const key = el.dataset.i18n;
    const value = t(key);
    if (value !== key) el.textContent = value;
  });
  $$("[data-i18n-placeholder]", root).forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const value = t(key);
    if (value !== key) el.placeholder = value;
  });
}

function initLanguage() {
  const saved = Store.getLang() || "en";
  setLanguage(saved);

  $$(".login-lang-switch .lang-btn").forEach(btn => {
    btn.onclick = () => setLanguage(btn.dataset.lang);
  });

  const langToggle = $("#langToggle");
  const langDropdown = $("#langDropdown");
  if (langToggle && langDropdown) {
    langToggle.onclick = (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle("hidden");
    };
    $$("[data-lang]", langDropdown).forEach(btn => {
      btn.onclick = () => {
        setLanguage(btn.dataset.lang);
        langDropdown.classList.add("hidden");
      };
    });
    document.addEventListener("click", (e) => {
      if (!langDropdown.contains(e.target) && !langToggle.contains(e.target)) {
        langDropdown.classList.add("hidden");
      }
    });
  }
}